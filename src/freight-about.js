// The other two pages are linked under the title, so Impressum is one click away from wherever the drawer opened.
export function aboutPage(id){
 if(!Object.hasOwn(ABOUT,id))return '';
 const others=Object.entries(ABOUT).filter(([k])=>k!==id).map(([k,x])=>page(k,x.title)).join(' · ');
 return `<h2>${ABOUT[id].title}</h2><p class="about-nav">${others}</p><div class="about">${ABOUT[id].html}</div>`;
}
